# Builds the multi-file site from source/intro/src.html into ./site (index.html + assets/intro/*)
import base64,os,re,sys,shutil
from PIL import Image
HERE=os.path.dirname(os.path.abspath(__file__))
SRC=sys.argv[1] if len(sys.argv)>1 else HERE           # folder with src.html, logo.webp, labels_rgb.png, script.json, cier.webp
OUT=sys.argv[2] if len(sys.argv)>2 else os.path.join(HERE,'site')
A=os.path.join(OUT,'assets','intro');os.makedirs(A,exist_ok=True)
s=open(os.path.join(SRC,'src.html'),encoding='utf-8').read()
b64=lambda f,m:'data:%s;base64,'%m+base64.b64encode(open(os.path.join(SRC,f),'rb').read()).decode()
# 1. CSS
css=re.search(r'<style>\n(.*?)</style>\n',s,re.S);s=s.replace(css.group(0),'<link rel="stylesheet" href="assets/intro/intro.css">\n')
open(os.path.join(A,'intro.css'),'w',encoding='utf-8').write(css.group(1))
# 2. logo data: kept as data URLs because the page reads their pixels (works from file:// too)
d=re.search(r'<script>\n(const SCRIPT=__SCRIPT__;\nconst LOGO_SRC="__LOGO__", LABEL_SRC="__LABELS__";\n)</script>\n',s)
data=d.group(1).replace('__SCRIPT__',open(os.path.join(SRC,'script.json'),encoding='utf-8').read().strip()).replace('__LOGO__',b64('logo.webp','image/webp')).replace('__LABELS__',b64('labels_rgb.png','image/png'))
open(os.path.join(A,'logo-data.js'),'w',encoding='utf-8').write('// Sargotsav logo artwork, stroke script and component labels (generated by build_site.py)\n'+data)
s=s.replace(d.group(0),'<script src="assets/intro/logo-data.js"></script>\n')
# 3. main JS
j=re.search(r'<script>\n(.*?)</script>\n',s,re.S);s=s.replace(j.group(0),'<script src="assets/intro/intro.js"></script>\n')
open(os.path.join(A,'intro.js'),'w',encoding='utf-8').write(j.group(1))
# 4. images
shutil.copy(os.path.join(SRC,'cier.webp'),os.path.join(A,'cier.webp'));s=s.replace('__CIER__','assets/intro/cier.webp')
shutil.copy(os.path.join(SRC,'msm.webp'),os.path.join(A,'msm.webp'));s=s.replace('__MSM__','assets/intro/msm.webp')
lg=Image.open(os.path.join(SRC,'logo.webp')).convert('RGBA')
fav=Image.new('RGBA',(512,512),(244,239,230,255));t=lg.copy();t.thumbnail((440,440));fav.paste(t,((512-t.width)//2,(512-t.height)//2),t)
fav.resize((192,192),Image.LANCZOS).save(os.path.join(A,'icon-192.png'));fav.resize((48,48),Image.LANCZOS).save(os.path.join(A,'favicon.png'))
s=s.replace('__FAVICON__','assets/intro/favicon.png').replace('<link rel="icon" href="assets/intro/favicon.png">','<link rel="icon" href="assets/intro/favicon.png">\n<link rel="apple-touch-icon" href="assets/intro/icon-192.png">')
og=os.path.join(SRC,'og.jpg')
if os.path.exists(og):shutil.copy(og,os.path.join(A,'og.jpg'))
s=s.replace('__OGIMG__','https://sargotsav-2026-kochi.vercel.app/assets/intro/og.jpg')  # crawlers (WhatsApp) need an absolute URL
assert '__' not in re.sub(r'window\.__\w+|__dbg|__frame|__ready|__TL','',s),'placeholder left'
open(os.path.join(OUT,'index.html'),'w',encoding='utf-8').write(s)
print('site written to',OUT)
